    """PRODUCTION host-tile code: the prefill-options helper block (tile_plan, host_tile_count, plan_units) and the
    HostStager class, for tools/cpu_fake/test_host_tiles.cpp (fake CUDA streams — FAKE_CUDA_ASYNC=1 makes them real threads)."""
    rt = (ROOT / 'engine/src/runtime.cpp').read_text()
    helpers = _slice(rt, 'const float* e4m3_lut() {', '// ---- Host helpers END')
    stager = _slice(rt, '// ---- Host tile staging BEGIN', '// ---- Host tile staging END')
