def objects(out_dir, sources):
    """Compile each source once. HIVE_TEST_BUILD_DIR (set by tools/test_cpu.sh / test_tsan_cpu.sh) shares
    objects between test scripts; the key is a hash of flags + source + every hive header, so a
    changed file is always recompiled."""
    import hashlib
    cache = Path(os.environ.get('HIVE_TEST_BUILD_DIR') or out_dir)
    cache.mkdir(parents=True, exist_ok=True)
    deps = ''.join(p.read_text() for p in sorted((ROOT / 'engine/include/hive').glob('*.h'))) + \
        ''.join(p.read_text() for p in sorted((FAKE / 'include').glob('*.h')))
    objs = []
    for src in sources:
        key = hashlib.sha1((' '.join(flags()) + Path(src).read_text() + deps).encode()).hexdigest()[:12]
        obj = cache / f'{Path(src).stem}-{key}.o'
        if not obj.exists():
            tmp = obj.with_suffix(f'.{os.getpid()}.tmp.o')
            subprocess.run(flags() + ['-c', str(src), '-o', str(tmp)], check=True)
            os.replace(tmp, obj)
        objs.append(obj)
    return objs


def build_daemon(out_dir, name='hived', hived_source=None):
    """The REAL engine/src/hived.cpp + expert_store.cpp + cpu kernels on fake CUDA/Runtime.
    hived_source: optional replacement text (negative-control mutants only; never written to the repo)."""
    gen = Path(out_dir) / 'fake_runtime_gen.cpp'
    gen.write_text(runtime_source())
    src = ROOT / 'engine/src/hived.cpp'
    if hived_source is not None:
        src = Path(out_dir) / (name + '_hived.cpp')
        src.write_text(hived_source)
    objs = objects(out_dir, [src, gen, ROOT / 'engine/src/expert_store.cpp', ROOT / 'engine/src/cpu/expert_cpu.cpp', FAKE / 'fake_checkpoint.cpp'])
    return build(out_dir, name, '', objs)


SUPP = FAKE / 'tsan-known-pool-race.supp'


def tsan_supp_env(env, keep=('items', 'dtor'), tmp_dir=None):
    """Known-race suppressions (tsan-known-pool-race.supp); `keep` selects the [tags] to suppress."""
    if sanitizer() != 'thread':
        return env
    path = SUPP
    if set(keep) != {'items', 'dtor'}:
        out, tag = [], None
        for line in SUPP.read_text().splitlines():
            if line.startswith('# [') and ']' in line:
                tag = line[3:line.index(']')]
            if line.startswith('race:') and tag in keep:
                out.append(line)
        path = Path(tmp_dir) / ('supp-' + '-'.join(keep or ('none',)) + '.supp')
        path.write_text('\n'.join(out) + '\n')
    opts = env.get('TSAN_OPTIONS', 'halt_on_error=1:exitcode=66')
    env['TSAN_OPTIONS'] = opts + ':suppressions=' + str(path)
    return env
