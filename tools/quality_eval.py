def _safe_eval(expr):
    expr = expr.replace("×", "*").replace("÷", "/").replace("^", "**").replace(",", "")
    node = ast.parse(expr, mode="eval")
    ops = {ast.Add: lambda a, b: a + b, ast.Sub: lambda a, b: a - b, ast.Mult: lambda a, b: a * b, ast.Div: lambda a, b: a / b,
           ast.Pow: lambda a, b: a ** b, ast.FloorDiv: lambda a, b: a // b, ast.Mod: lambda a, b: a % b}

    def ev(n):
        if isinstance(n, ast.Expression):
            return ev(n.body)
        if isinstance(n, ast.Constant) and isinstance(n.value, (int, float)):
            return n.value
        if isinstance(n, ast.BinOp) and type(n.op) in ops:
            return ops[type(n.op)](ev(n.left), ev(n.right))
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, (ast.USub, ast.UAdd)):
            return -ev(n.operand) if isinstance(n.op, ast.USub) else ev(n.operand)
        raise ValueError("unsupported expression")
    return ev(node)


def check_args(args, spec):
    bad = []
    for key, how, want in spec:
        v = args.get(key)
        ok = False
        try:
            if how == "ieq":
                ok = str(v).strip().lower() == str(want).lower()
            elif how == "upper":
                ok = str(v).strip().upper() == want
            elif how == "alias":
                ok = any(str(v).strip().lower() == a.lower() or str(v).strip().lower().startswith(a.lower() + ",") for a in want)
            elif how == "num":
                ok = abs(float(v) - float(want)) < 1e-6
            elif how == "expr":
                ok = abs(float(_safe_eval(str(v))) - float(want)) < 1e-6
            elif how == "has":
                ok = all(w.lower() in str(v).lower() for w in want)
        except (ValueError, TypeError, SyntaxError, ZeroDivisionError):
            ok = False
        if not ok:
            bad.append(f"{key}={v!r}")
    return bad


