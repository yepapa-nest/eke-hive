def run_item(h, it, seed):
    if it["suite"] == "tool":
        return run_tool_item(h, it, seed)
    r = openai_call(h, it["messages"], it["max_tokens"], seed, stream=it.get("stream", True))
    base = {"latency_s": r.get("latency"), "ttft_s": r.get("ttft"), "prompt_tokens": r.get("prompt_tokens"), "completion_tokens": r.get("completion_tokens"),
            "output": r["content"]}
    if r["error"]:
        return {**base, "pass": False, "detail": {"error": r["error"]}}
    if it["check"] == "code":
        code = extract_code(r["content"])
        ok, why = run_code(code, it["expected"]["tests"])
        return {**base, "pass": ok, "detail": {"sandbox": why, "finish": r["finish"]}}
    ok, ex = check_answer(it["check"], it["expected"], r["content"])
    return {**base, "pass": ok, "detail": {"extracted": ex, "finish": r["finish"]}}


