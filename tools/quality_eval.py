def calibrate(h, filler, langs, seed):
    """Filler characters/token ratio — send N and 2N characters with the same template and measure via the usage.prompt_tokens difference (fixed tokenizer → identical across both runs)."""
    cpt = {}
    for lang in langs:
        src = filler.source(lang)
        if src in cpt:
            continue
        toks = []
        for n in (6000, 12000):
            text = filler.get(random.Random(f"{seed}:cal:{src}"), n, lang)
            r = openai_call(h, [{"role": "user", "content": text + "\n\nReply with OK."}], 1, seed, stream=False)
            if r.get("error") or not r.get("prompt_tokens"):
                raise RuntimeError(f"calibration failed ({src}): {r.get('error')}")
            toks.append(r["prompt_tokens"])
        cpt[src] = round(6000.0 / max(1, toks[1] - toks[0]), 3)
    return cpt


