def openai_call(h, messages, max_tokens, seed, stream=True, tools=None, extra=None):
    """→ dict(status, content, reasoning, tool_calls, finish, latency, ttft, prompt_tokens, completion_tokens, hive, error, n_chunks)."""
    body = {"model": "hive", "messages": messages, "max_tokens": max_tokens, "temperature": 0.0, "seed": seed, "stream": stream}
    if tools:
        body["tools"] = tools
    body.update(extra if extra is not None else NOTHINK)
    if extra is None and THINK_EXTRA[0]:
        body["max_tokens"] = max_tokens + THINK_EXTRA[0]
    out = {"content": "", "reasoning": "", "tool_calls": [], "finish": None, "ttft": None, "prompt_tokens": None,
           "completion_tokens": None, "hive": None, "error": None, "n_chunks": 0}
    if not stream:
        st, j, lat = h.post("/v1/chat/completions", body)
        out.update(status=st, latency=lat)
        if st != 200:
            out["error"] = f"HTTP {st}: {json.dumps(j, ensure_ascii=False)[:500]}"
            return out
        ch = (j.get("choices") or [{}])[0]
        m = ch.get("message") or {}
        u = j.get("usage") or {}
        out.update(content=m.get("content") or "", reasoning=m.get("reasoning_content") or "", tool_calls=m.get("tool_calls") or [],
                   finish=ch.get("finish_reason"), prompt_tokens=u.get("prompt_tokens"), completion_tokens=u.get("completion_tokens"),
                   hive=j.get("hive"))
        pm = (j.get("hive") or {}).get("prefill_ms")
        out["ttft"] = pm / 1000.0 if isinstance(pm, (int, float)) else None  # non-streaming: daemon prefill time ≈ TTFT
        out["ttft_src"] = "hive.prefill_ms"
        return out
    st, evs, lat = h.stream("/v1/chat/completions", body)
    out.update(status=st, latency=lat, ttft_src="first delta")
    calls = {}
    for t, d in evs:
        if "_http_error" in d:
            out["error"] = f"HTTP {st}: {d['_http_error'][:500]}"
            continue
        if d.get("error"):
            out["error"] = json.dumps(d["error"], ensure_ascii=False)[:500]
            continue
        if "choices" not in d:
            continue
        out["n_chunks"] += 1
        if d.get("usage"):
            out["prompt_tokens"] = d["usage"].get("prompt_tokens")
            out["completion_tokens"] = d["usage"].get("completion_tokens")
        for c in d["choices"]:
            dl = c.get("delta") or {}
            got = False
            if dl.get("content"):
                out["content"] += dl["content"]; got = True
            if dl.get("reasoning_content"):
                out["reasoning"] += dl["reasoning_content"]; got = True
            for tc in dl.get("tool_calls") or []:
                got = True
                k = tc.get("index", len(calls))
                cur = calls.setdefault(k, {"id": tc.get("id"), "type": "function", "function": dict(name="", arguments="")})
                fn = tc.get("function") or {}
                cf = cur["function"]
                cf["name"] += fn.get("name") or ""
                cf["arguments"] += fn.get("arguments") or ""
                if tc.get("id"):
                    cur["id"] = tc["id"]
            if got and out["ttft"] is None:
                out["ttft"] = t
            if c.get("finish_reason"):
                out["finish"] = c["finish_reason"]
    out["tool_calls"] = [calls[k] for k in sorted(calls)]
    if out["finish"] is None and not out["error"]:
        out["error"] = "stream ended without finish_reason"
    return out


def anthropic_call(h, messages, max_tokens, stream=True, thinking=False, tools=None, system=None):
    body = {"model": "hive", "messages": messages, "max_tokens": max_tokens, "temperature": 0.0, "stream": stream}
    if not thinking:
        body["thinking"] = {"type": "disabled"}
    if tools:
        body["tools"] = tools
    if system:
        body["system"] = system
    out = {"text": "", "thinking": "", "tool_use": [], "stop_reason": None, "ttft": None, "error": None, "events": 0,
           "event_types": {}, "input_tokens": None, "output_tokens": None}
    if not stream:
        st, j, lat = h.post("/v1/messages", body)
        out.update(status=st, latency=lat)
        if st != 200:
            out["error"] = f"HTTP {st}: {json.dumps(j, ensure_ascii=False)[:500]}"
            return out
        for b in j.get("content") or []:
            if b.get("type") == "text":
                out["text"] += b.get("text", "")
            elif b.get("type") == "thinking":
                out["thinking"] += b.get("thinking", "")
            elif b.get("type") == "tool_use":
                out["tool_use"].append({"name": b.get("name"), "input": b.get("input")})
        out["stop_reason"] = j.get("stop_reason")
        u = j.get("usage") or {}
        out.update(input_tokens=u.get("input_tokens"), output_tokens=u.get("output_tokens"))
        return out
    st, evs, lat = h.stream("/v1/messages", body)
    out.update(status=st, latency=lat)
    tool_json = {}
    for t, d in evs:
        if "_http_error" in d:
            out["error"] = f"HTTP {st}: {d['_http_error'][:500]}"
            continue
        ty = d.get("type")
        if not ty:
            continue
        out["events"] += 1
        out["event_types"][ty] = out["event_types"].get(ty, 0) + 1
        if ty == "error":
            out["error"] = json.dumps(d.get("error"), ensure_ascii=False)[:500]
        elif ty == "message_start":
            out["input_tokens"] = ((d.get("message") or {}).get("usage") or {}).get("input_tokens")
        elif ty == "content_block_start":
            cb = d.get("content_block") or {}
            if cb.get("type") == "tool_use":
                tool_json[d.get("index")] = {"name": cb.get("name"), "json": ""}
        elif ty == "content_block_delta":
            dl = d.get("delta") or {}
            if out["ttft"] is None:
                out["ttft"] = t
            if dl.get("type") == "text_delta":
                out["text"] += dl.get("text", "")
            elif dl.get("type") == "thinking_delta":
                out["thinking"] += dl.get("thinking", "")
            elif dl.get("type") == "input_json_delta" and d.get("index") in tool_json:
                tool_json[d["index"]]["json"] += dl.get("partial_json", "")
        elif ty == "message_delta":
            out["stop_reason"] = (d.get("delta") or {}).get("stop_reason")
            u = d.get("usage") or {}
            out["output_tokens"] = u.get("output_tokens")
    for k in sorted(tool_json, key=lambda x: (x is None, x)):
        tj = tool_json[k]
        try:
            inp = json.loads(tj["json"]) if tj["json"] else {}
        except ValueError:
            inp = {"_raw": tj["json"]}
        out["tool_use"].append({"name": tj["name"], "input": inp})
    if out["stop_reason"] is None and not out["error"]:
        out["error"] = "stream ended without message_delta.stop_reason"
    return out


