def _first_call(r):
    for c in r.get("tool_calls") or []:
        fn = c.get("function") or {}
        try:
            args = json.loads(fn.get("arguments") or "{}")
        except ValueError:
            return fn.get("name"), None, c.get("id")
        return fn.get("name"), args if isinstance(args, dict) else None, c.get("id")
    return None, None, None


def run_tool_item(h, it, seed):
    exp = it["expected"]
    if it["check"] == "tool_anthropic":
        atools = [{"name": t["function"]["name"], "description": t["function"]["description"], "input_schema": t["function"]["parameters"]} for t in TOOLS]
        r = anthropic_call(h, it["messages"], it["max_tokens"], stream=False, tools=atools)
        tu = r["tool_use"][0] if r["tool_use"] else {}
        bad = check_args(tu.get("input") or {}, exp["args"]) if tu.get("name") == exp["name"] else [f"name={tu.get('name')!r}"]
        return {"pass": not r["error"] and not bad, "latency_s": r.get("latency"), "ttft_s": None, "prompt_tokens": r["input_tokens"],
                "completion_tokens": r["output_tokens"], "output": json.dumps(r["tool_use"], ensure_ascii=False) + r["text"],
                "detail": {"bad": bad, "stop_reason": r["stop_reason"], "error": r["error"]}}
    r = openai_call(h, it["messages"], it["max_tokens"], seed, stream=it.get("stream", True), tools=it["tools"])
    name, args, cid = _first_call(r)
    res = {"latency_s": r.get("latency"), "ttft_s": r.get("ttft"), "prompt_tokens": r.get("prompt_tokens"), "completion_tokens": r.get("completion_tokens"),
           "output": json.dumps(r["tool_calls"], ensure_ascii=False) + "\n" + r["content"]}
    if it["check"] == "tool":
        if exp["name"] is None:
            bad = ([f"unexpected call {name}"] if name else []) + check_args({"content": r["content"]}, exp["args"])
        elif name != exp["name"]:
            bad = [f"name={name!r}"]
        elif args is None:
            bad = ["arguments not a JSON object"]
        else:
            bad = check_args(args, exp["args"])
        res.update(detail={"bad": bad, "finish": r["finish"], "error": r["error"]}, **{"pass": not r["error"] and not bad})
        return res
    # follow-up turn: if the first-turn call was correct, put the model's own call in the history, otherwise a fixed call, and have it answer from the tool result
    call = exp["call"]
    first_ok = name == call["name"] and args is not None
    cid = cid or "call_qe_0"
    targs = json.dumps(args if first_ok else call["arguments"], ensure_ascii=False)
    msgs = it["messages"] + [{"role": "assistant", "content": "", "tool_calls": [{"id": cid, "type": "function", "function": {"name": call["name"], "arguments": targs}}]},
                             {"role": "tool", "tool_call_id": cid, "content": json.dumps(exp["result"])}]
    r2 = openai_call(h, msgs, it["max_tokens"], seed, stream=True, tools=it["tools"])
    txt = r2["content"]
    ok2 = all((any(a in txt for a in m) if isinstance(m, (tuple, list)) else m in txt) for m in exp["must"])
    res.update({"pass": bool(first_ok and ok2 and not r["error"] and not r2["error"]), "latency_s": (r.get("latency") or 0) + (r2.get("latency") or 0),
                "ttft2_s": r2.get("ttft"), "completion_tokens": (r.get("completion_tokens") or 0) + (r2.get("completion_tokens") or 0),
                "output": res["output"] + "\n---\n" + txt,
                "detail": {"first_call_ok": first_ok, "first": [name, args], "answer_ok": ok2, "error": r["error"] or r2["error"]}})
    return res


