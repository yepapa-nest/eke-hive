def _qa_string(rng, lang, i):
    w = rng.choice(_WORDS)
    t = i % 3
    if t == 0:
        return (f"영어 단어 \"{w}\"의 글자 순서를 거꾸로 뒤집어 쓰세요." if lang == "ko" else f"Write the word \"{w}\" with its letters in reverse order."), "str", w[::-1]
    if t == 1:
        ch = rng.choice(sorted(set(w)))
        return (f"영어 단어 \"{w}\"에 글자 '{ch}'가 몇 번 나옵니까?" if lang == "ko" else f"How many times does the letter '{ch}' appear in the word \"{w}\"?"), "num", w.count(ch)
    return (f"영어 단어 \"{w}\"는 몇 글자입니까?" if lang == "ko" else f"How many letters are in the word \"{w}\"?"), "num", len(w)


def _qa_logic(rng, lang, i):
    if i % 2 == 0:
        names = list(_NAMES_KO if lang == "ko" else _NAMES_EN)
        order = names[:]
        rng.shuffle(order)  # order[0] = largest
        pairs = [(order[j], order[j + 1]) for j in range(3)]
        rng.shuffle(pairs)
        tallest = rng.random() < 0.5
        if lang == "ko":
            josa = lambda w: "은" if (ord(w[-1]) - 0xAC00) % 28 else "는"  # topic particle "eun" after a final consonant, otherwise "neun"
            facts = " ".join(f"{a}{josa(a)} {b}보다 키가 큽니다." for a, b in pairs)
            q = f"{facts} 네 사람 중 키가 가장 {'큰' if tallest else '작은'} 사람은 누구입니까? 이름으로 답하세요."
        else:
            facts = " ".join(f"{a} is taller than {b}." for a, b in pairs)
            q = f"{facts} Who is the {'tallest' if tallest else 'shortest'} of the four? Answer with the name."
        return q, "str", order[0] if tallest else order[-1]
    x, y = rng.randrange(5, 60), rng.randrange(1, 40)
    q = (f"두 수 x, y에 대해 x + y = {x + y}, x − y = {x - y} 입니다. x는 얼마입니까?" if lang == "ko"
         else f"Two numbers satisfy x + y = {x + y} and x - y = {x - y}. What is x?")
    return q, "num", x


