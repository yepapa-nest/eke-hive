_WD_EN = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]
_WD_KO = ["월요일", "화요일", "수요일", "목요일", "금요일", "토요일", "일요일"]
_ANS_RE = re.compile(r"(?:최종\s*정답|정답|최종\s*답|final\s+answer|answer)\s*(?:은|는)?\s*[:：]\s*(.+)", re.I)


def extract_final(text):
    """X of the last 'Answer: X' (or its Korean equivalent). None if absent. Strips markdown emphasis, quotes and trailing punctuation."""
    if not text:
        return None
    last = None
    for line in text.splitlines():
        s = line.strip().replace("**", "").replace("__", "")
        m = _ANS_RE.search(s)
        if m:
            last = m.group(1)
    if last is None:
        return None
    s = last.strip().strip("`*_\"'“”‘’ ").strip()
    s = re.sub(r"\\boxed\{(.*)\}", r"\1", s)
    s = s.rstrip(".。!")
    return s.strip()


def _num_in(s):
    if s is None:
        return None
    m = re.search(r"-?\d+(?:\.\d+)?", s.replace(",", ""))
    return float(m.group(0)) if m else None


def _norm(s):
    return re.sub(r"\s+", " ", (s or "").strip().strip(".").strip()).lower()


def check_answer(kind, expected, text):
    """→ (pass, extracted)."""
    if kind == "contains":
        return (str(expected).lower() in (text or "").lower()), None
    if kind == "contains_all":
        low = (text or "").lower()
        return all(str(e).lower() in low for e in expected), None
    if kind == "names_exact":  # variable tracking: all expected names + no distractor names
        want, bad = expected
        found = set(re.findall(r"\b[A-Z]{5}\b", text or ""))
        return (set(want) <= found and not (set(bad) & found)), sorted(found)
    ex = extract_final(text)
    if kind == "num":
        v = _num_in(ex)
        return (v is not None and abs(v - float(expected)) < 1e-6), ex
    if ex is None:
        return False, None
    if kind == "str":
        return _norm(ex) == _norm(str(expected)), ex
    if kind == "alias":
        e = _norm(ex)
        return any(_norm(a) == e or re.search(r"(?<![a-z0-9])" + re.escape(_norm(a)) + r"(?![a-z0-9])", e) for a in expected), ex
    if kind == "date":
        m = re.search(r"(\d{4})\D{1,3}(\d{1,2})\D{1,3}(\d{1,2})", ex)
        return (m is not None and "%04d-%02d-%02d" % tuple(int(x) for x in m.groups()) == expected), ex
    if kind == "weekday":
        e = ex.lower()
        hit = [i for i, (a, b) in enumerate(zip(_WD_EN, _WD_KO)) if a in e or b in ex or (len(ex) <= 3 and ex.strip() == b[0])]
        return (hit == [expected]), ex
    raise ValueError(kind)


