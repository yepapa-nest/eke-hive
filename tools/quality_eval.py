def gen_prose(rng, n_chars, lang):
    out, n = [], 0
    while n < n_chars:
        if lang == "ko":
            s = f"{rng.choice(_KO_WHEN)} {rng.choice(_KO_SUBJ)} {rng.choice(_KO_OBJ)} {rng.choice(_KO_VERB)}"
        else:
            s = f"{rng.choice(_EN_SUBJ)} {rng.choice(_EN_VERB)} {rng.choice(_EN_OBJ)} {rng.choice(_EN_TAIL)}"
        out.append(s)
        n += len(s) + 1
        if rng.random() < 0.12:
            out.append("\n\n")
    return " ".join(out)[:n_chars]


class Filler:
    """Natural-language filler. With --corpus, cut from that file at seed-fixed offsets; otherwise generated."""
    def __init__(self, corpus_path=None):
        self.corpus = None
        if corpus_path:
            with open(corpus_path, encoding="utf-8", errors="replace") as f:
                self.corpus = f.read()

    def source(self, lang):
        return "corpus" if self.corpus else lang

    def get(self, rng, n_chars, lang):
        if self.corpus:
            c = self.corpus
            if len(c) < n_chars + 1:
                c = c * (n_chars // max(1, len(c)) + 2)
            off = rng.randrange(0, max(1, len(c) - n_chars))
            return c[off:off + n_chars]
        return gen_prose(rng, n_chars, lang)


def _insert_at(text, depth, needle):
    """Insert needle at a sentence boundary near depth (0..1)."""
    pos = int(len(text) * depth)
    for sep in (". ", "다. ", "\n"):
        j = text.find(sep, pos)
        if 0 <= j < pos + 400:
            pos = j + len(sep)
            break
    return text[:pos] + " " + needle + " " + text[pos:]


def _key(rng):
    a = ["amber", "cobalt", "silent", "crimson", "velvet", "hollow", "golden", "frozen", "rapid", "lunar", "misty", "ivory"]
    b = ["falcon", "harbor", "lantern", "meadow", "comet", "willow", "canyon", "piano", "orchid", "glacier", "beacon", "tundra"]
    return f"{rng.choice(a)}-{rng.choice(b)}-{rng.randrange(10, 99)}"


def _val(rng):
    return str(rng.randrange(1000000, 9999999))


def _vname(rng, used):
    while True:
        v = "".join(rng.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") for _ in range(5))
        if v not in used:
            used.add(v)
            return v


