def _qa_arith(rng, lang, i):
    t = i % 4
    if t == 0:
        p, n = rng.randrange(2, 9), rng.randrange(3, 12)
        bill = 100 if p * n < 100 else 200
        ans = bill - p * n
        q = (f"연필 한 자루가 {p}달러입니다. 민수가 연필 {n}자루를 사고 {bill}달러 지폐로 냈습니다. 거스름돈은 몇 달러입니까?" if lang == "ko"
             else f"Pencils cost {p} dollars each. Tom buys {n} pencils and pays with a {bill}-dollar bill. How many dollars of change does he get?")
    elif t == 1:
        v, h1, v2, h2 = rng.randrange(40, 120), rng.randrange(2, 6), rng.randrange(30, 90), rng.randrange(1, 5)
        ans = v * h1 + v2 * h2
        q = (f"기차가 시속 {v}km로 {h1}시간 달린 뒤 시속 {v2}km로 {h2}시간 더 달렸습니다. 모두 몇 km를 달렸습니까?" if lang == "ko"
             else f"A train travels at {v} km/h for {h1} hours, then at {v2} km/h for {h2} hours. How many kilometers does it travel in total?")
    elif t == 2:
        a, b, c = rng.randrange(3, 9), rng.randrange(4, 12), rng.randrange(1, 10)
        ans = a * b - c
        q = (f"달걀 상자에 {a}줄, 줄마다 {b}개씩 달걀이 들어 있습니다. 그중 {c}개가 깨졌습니다. 남은 달걀은 몇 개입니까?" if lang == "ko"
             else f"A box holds {a} rows of {b} eggs. {c} eggs break. How many eggs are left?")
    else:
        w, per, hrs = rng.randrange(3, 15), rng.randrange(5, 25), rng.randrange(2, 9)
        ans = w * per * hrs
        q = (f"작업자 {w}명이 각자 시간당 부품 {per}개를 만듭니다. {hrs}시간 동안 모두 몇 개를 만듭니까?" if lang == "ko"
             else f"{w} workers each make {per} parts per hour. How many parts do they make in {hrs} hours?")
    return q, "num", ans


