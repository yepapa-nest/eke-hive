class Http:
    def __init__(self, base, timeout=1800):
        u = urllib.parse.urlparse(base)
        self.host, self.port = u.hostname, u.port or (443 if u.scheme == "https" else 80)
        self.https = u.scheme == "https"
        self.timeout = timeout

    def _conn(self):
        cls = http.client.HTTPSConnection if self.https else http.client.HTTPConnection
        return cls(self.host, self.port, timeout=self.timeout)

    def get(self, path):
        c = self._conn()
        try:
            c.request("GET", path)
            r = c.getresponse()
            return r.status, r.read().decode("utf-8", "replace")
        finally:
            c.close()

    def post(self, path, body):
        c = self._conn()
        t0 = time.time()
        try:
            data = json.dumps(body, ensure_ascii=False).encode()
            c.request("POST", path, body=data, headers={"Content-Type": "application/json"})
            r = c.getresponse()
            raw = r.read().decode("utf-8", "replace")
            dtm = time.time() - t0
            try:
                j = json.loads(raw)
            except ValueError:
                j = {"_raw": raw[:2000]}
            return r.status, j, dtm
        finally:
            c.close()

    def stream(self, path, body):
        """SSE: [(t_rel, data_dict)] + status. Only data lines are parsed (Anthropic's event: lines equal data.type)."""
        c = self._conn()
        t0 = time.time()
        events = []
        try:
            data = json.dumps(body, ensure_ascii=False).encode()
            c.request("POST", path, body=data, headers={"Content-Type": "application/json"})
            r = c.getresponse()
            if r.status != 200:
                return r.status, [(time.time() - t0, {"_http_error": r.read().decode("utf-8", "replace")[:2000]})], time.time() - t0
            while True:
                line = r.readline()
                if not line:
                    break
                line = line.decode("utf-8", errors="replace").rstrip("\r\n")
                if not line.startswith("data:"):
                    continue
                payload = line[5:].strip()
                if payload == "[DONE]":
                    events.append((time.time() - t0, {"_done": True}))
                    break
                try:
                    events.append((time.time() - t0, json.loads(payload)))
                except ValueError:
                    events.append((time.time() - t0, {"_bad": payload[:500]}))
            return 200, events, time.time() - t0
        finally:
            c.close()


