        for i, s in enumerate(nst):
            hay = _insert_at(hay, 0.2 + 0.25 * i, s)
        q = (f"Memorize and track the chain(s) of variable assignments hidden in the text above. Find all variables that are assigned the "
             f"value {v}, directly or through other variables. Answer with the variable names only, separated by commas.")
        exp_kind, expected, max_tokens = "names_exact", [chain, noise], 64
