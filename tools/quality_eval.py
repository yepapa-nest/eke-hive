def ruler_item(seed, length, kind, lang, depth, filler, cpt):
    rng = random.Random(f"{seed}:ruler:{length}:{kind}")
    n_chars = max(200, int(length * cpt[filler.source(lang)] * 0.96))
    hay = filler.get(rng, n_chars, lang)
    exp_kind, expected, max_tokens = "contains", None, 48
    if kind.startswith("single"):
        k, v = _key(rng), _val(rng)
        needle = (f"{k}의 특별한 마법 숫자는 {v}입니다." if lang == "ko" else f"The special magic number for {k} is {v}.")
        hay = _insert_at(hay, depth, needle)
        q = (f"위 글에 숨겨진 {k}의 특별한 마법 숫자는 무엇입니까? 숫자만 답하세요." if lang == "ko"
             else f"What is the special magic number for {k} mentioned in the text above? Answer with the number only.")
        expected = v
    elif kind == "multikey":
        keys = [_key(rng) for _ in range(4)]
        vals = [_val(rng) for _ in range(4)]
        for i, (k, v) in enumerate(zip(keys, vals)):
            hay = _insert_at(hay, 0.15 + 0.22 * i, f"{k}의 특별한 마법 숫자는 {v}입니다." if lang == "ko" else f"The special magic number for {k} is {v}.")
        t = rng.randrange(4)
        q = (f"위 글에 숨겨진 {keys[t]}의 특별한 마법 숫자는 무엇입니까? 숫자만 답하세요." if lang == "ko"
             else f"What is the special magic number for {keys[t]}? Answer with the number only.")
        expected = vals[t]
    elif kind == "multivalue":
        k = _key(rng)
        vals = [_val(rng) for _ in range(4)]
        for i, v in enumerate(vals):
            hay = _insert_at(hay, 0.12 + 0.24 * i, f"One of the special magic numbers for {k} is {v}.")
        q = f"The text above contains several special magic numbers for {k}. List all of them, separated by commas. Answer with the numbers only."
